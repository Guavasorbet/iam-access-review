"""Run the access review: join the data sources, apply every rule, write results.

Outputs:
    reports/findings.csv      every finding, one row each (for auditors / Excel)
    reports/summary.md        short written summary of the review
    docs/findings.js          data file the dashboard reads (GitHub Pages)

Usage:
    python review/run_review.py
    python review/run_review.py --review-date 2026-10-31
"""

import argparse
import csv
import json
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "review"))
from rules import RULES, SEVERITY_ORDER, evaluate_person  # noqa: E402

DATA, DOCS, REPORTS = ROOT / "data", ROOT / "docs", ROOT / "reports"


def read_csv(name):
    with (DATA / name).open(newline="") as f:
        return list(csv.DictReader(f))


def load_people():
    """Join HR roster, directory accounts, entitlements and badges on user_id."""
    accounts = {r["user_id"]: r for r in read_csv("directory_accounts.csv")}
    badges = {r["user_id"]: r for r in read_csv("badge_access.csv")}
    ents = defaultdict(list)
    for r in read_csv("entitlements.csv"):
        ents[r["user_id"]].append(r)
    people = []
    for ident in read_csv("hr_roster.csv"):
        uid = ident["user_id"]
        people.append({"identity": ident, "account": accounts[uid],
                       "entitlements": ents[uid], "badge": badges.get(uid)})
    return people


def run(review_date: date):
    policy = json.loads((DATA / "policy.json").read_text())
    people = load_people()
    findings = []
    for p in people:
        findings.extend(evaluate_person(p, policy, review_date))
    findings.sort(key=lambda f: (SEVERITY_ORDER[f["severity"]], f["rule_id"], f["user_id"]))
    for i, f in enumerate(findings, 1):
        f["finding_id"] = f"F-{i:04d}"

    flagged = {f["user_id"] for f in findings}
    summary = {
        "company": policy["company"],
        "review_date": review_date.isoformat(),
        "identities": len(people),
        "accounts_enabled": sum(p["account"]["account_enabled"] == "true" for p in people),
        "badges_active": sum(bool(p["badge"]) and p["badge"]["badge_status"] == "Active" for p in people),
        "entitlements": sum(len(p["entitlements"]) for p in people),
        "users_with_findings": len(flagged),
        "clean_pct": round(100 * (len(people) - len(flagged)) / len(people), 1),
        "by_severity": {s: sum(f["severity"] == s for f in findings) for s in SEVERITY_ORDER},
        "by_rule": [{"rule_id": r.rule_id, "name": r.name, "severity": r.severity, "control": r.control,
                     "count": sum(f["rule_id"] == r.rule_id for f in findings)} for r in RULES.values()],
        "by_department": dict(Counter(f["department"] for f in findings).most_common()),
    }
    return summary, findings


def write_outputs(summary, findings):
    REPORTS.mkdir(exist_ok=True)
    cols = ["finding_id", "severity", "rule_id", "rule", "user_id", "name", "department", "title",
            "employment_type", "detail", "control", "action"]
    with (REPORTS / "findings.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(findings)

    sev = summary["by_severity"]
    lines = [
        f"# Access Review Summary: {summary['company']}",
        "",
        f"Review date: {summary['review_date']}",
        "",
        f"- Identities reviewed: {summary['identities']}",
        f"- Entitlements reviewed: {summary['entitlements']}",
        f"- People with at least one finding: {summary['users_with_findings']} "
        f"({100 - summary['clean_pct']:.1f}%)",
        f"- Findings: {sum(sev.values())} total — {sev['Critical']} Critical, {sev['High']} High, "
        f"{sev['Medium']} Medium, {sev['Low']} Low",
        "",
        "| Rule | Finding | Severity | NIST 800-53 | Count |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {r['rule_id']} | {r['name']} | {r['severity']} | {r['control']} | {r['count']} |"
              for r in summary["by_rule"]]
    (REPORTS / "summary.md").write_text("\n".join(lines) + "\n")

    payload = json.dumps({"summary": summary, "findings": findings}, indent=1)
    (DOCS / "findings.js").write_text(
        "// Generated by review/run_review.py — do not edit by hand.\n"
        f"window.ACCESS_REVIEW = {payload};\n")


def main():
    parser = argparse.ArgumentParser(description="Run the IAM access review.")
    parser.add_argument("--review-date", default="2026-10-31", help="YYYY-MM-DD")
    args = parser.parse_args()
    summary, findings = run(date.fromisoformat(args.review_date))
    write_outputs(summary, findings)
    sev = summary["by_severity"]
    print(f"Reviewed {summary['identities']} identities: {len(findings)} findings "
          f"({sev['Critical']} Critical, {sev['High']} High, {sev['Medium']} Medium, {sev['Low']} Low).")
    print("Wrote reports/findings.csv, reports/summary.md and docs/findings.js")


if __name__ == "__main__":
    main()
